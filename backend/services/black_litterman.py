"""
backend/services/black_litterman.py
===================================
Institutional Black-Litterman Asset Allocation Engine.
Blends market equilibrium returns with views generated by the Autonomous Research Engine
to compute mathematically coherent posterior expected returns and optimal portfolio weights.

Reference:
He, G., & Litterman, R. (1999). The Intuition Behind Black-Litterman Model Portfolios.
"""

from __future__ import annotations

import logging
import numpy as np
import pandas as pd
from dataclasses import dataclass, field, asdict
from typing import Dict, Any, List, Optional, Tuple

logger = logging.getLogger("wealth_advisor.services.black_litterman")


@dataclass
class ResearchView:
    asset: str
    relative_to: Optional[str] = None  # None for absolute view; symbol for relative view
    expected_return: float = 0.10      # e.g. 0.10 for 10%
    confidence: float = 0.70           # 0.0 to 1.0 (higher = lower uncertainty Omega)
    rationale: str = ""

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)


@dataclass
class BlackLittermanResult:
    assets: List[str]
    equilibrium_returns: Dict[str, float]
    posterior_returns: Dict[str, float]
    prior_weights: Dict[str, float]
    optimal_weights: Dict[str, float]
    weight_shifts: Dict[str, float]
    views_applied: List[ResearchView]

    def to_dict(self) -> Dict[str, Any]:
        return {
            "assets": self.assets,
            "equilibrium_returns": {k: round(v, 4) for k, v in self.equilibrium_returns.items()},
            "posterior_returns": {k: round(v, 4) for k, v in self.posterior_returns.items()},
            "prior_weights": {k: round(v, 4) for k, v in self.prior_weights.items()},
            "optimal_weights": {k: round(v, 4) for k, v in self.optimal_weights.items()},
            "weight_shifts": {k: round(v, 4) for k, v in self.weight_shifts.items()},
            "views_applied": [v.to_dict() for v in self.views_applied],
        }


def compute_black_litterman(
    assets: List[str],
    cov_matrix: np.ndarray,
    market_weights: Optional[np.ndarray] = None,
    views: Optional[List[ResearchView]] = None,
    risk_aversion: float = 2.5,
    tau: float = 0.05,
) -> BlackLittermanResult:
    """
    Computes the Black-Litterman posterior expected return and optimal weights.
    """
    n = len(assets)
    if n == 0:
        raise ValueError("Assets list cannot be empty")

    sigma = np.array(cov_matrix, dtype=float)
    if sigma.shape != (n, n):
        # Default diagonal covariance if not matched
        sigma = np.diag([0.04] * n)

    if market_weights is None:
        w_mkt = np.ones(n) / n
    else:
        w_mkt = np.array(market_weights, dtype=float)
        w_mkt = w_mkt / np.sum(w_mkt)

    # 1. Equilibrium implied returns: Pi = delta * Sigma * w_mkt
    pi = risk_aversion * (sigma @ w_mkt)

    if not views:
        # No views -> equilibrium weights
        w_opt = w_mkt
        return BlackLittermanResult(
            assets=assets,
            equilibrium_returns=dict(zip(assets, pi)),
            posterior_returns=dict(zip(assets, pi)),
            prior_weights=dict(zip(assets, w_mkt)),
            optimal_weights=dict(zip(assets, w_opt)),
            weight_shifts={a: 0.0 for a in assets},
            views_applied=[],
        )

    k = len(views)
    p = np.zeros((k, n))
    q = np.zeros(k)
    omega_diag = np.zeros(k)

    asset_idx = {sym: idx for idx, sym in enumerate(assets)}

    for i, view in enumerate(views):
        if view.asset not in asset_idx:
            continue
        idx_a = asset_idx[view.asset]

        if view.relative_to and view.relative_to in asset_idx:
            idx_b = asset_idx[view.relative_to]
            p[i, idx_a] = 1.0
            p[i, idx_b] = -1.0
        else:
            p[i, idx_a] = 1.0

        q[i] = view.expected_return

        # Confidence modulates uncertainty Omega: higher confidence -> smaller uncertainty
        conf = max(0.01, min(0.99, view.confidence))
        uncertainty_scale = (1.0 - conf) / conf
        # Variance of view from prior: p_i * (tau * Sigma) * p_i^T
        v_var = float(p[i : i + 1] @ (tau * sigma) @ p[i : i + 1].T)
        omega_diag[i] = max(1e-6, v_var * uncertainty_scale)

    omega = np.diag(omega_diag)

    # 2. Posterior Return Formula:
    # mu_BL = [ (tau*Sigma)^-1 + P^T Omega^-1 P ]^-1 * [ (tau*Sigma)^-1 * Pi + P^T Omega^-1 Q ]
    tau_sigma = tau * sigma
    inv_tau_sigma = np.linalg.pinv(tau_sigma)
    inv_omega = np.linalg.pinv(omega)

    m1 = inv_tau_sigma + (p.T @ inv_omega @ p)
    m1_inv = np.linalg.pinv(m1)

    m2 = (inv_tau_sigma @ pi) + (p.T @ inv_omega @ q)
    mu_bl = m1_inv @ m2

    # 3. Unconstrained optimal weights: w* = (delta * Sigma)^-1 * mu_bl
    inv_sigma = np.linalg.pinv(risk_aversion * sigma)
    raw_weights = inv_sigma @ mu_bl

    # Project onto simplex: non-negative weights summing to 1.0 (long-only)
    pos_weights = np.maximum(0.0, raw_weights)
    s = np.sum(pos_weights)
    w_opt = pos_weights / s if s > 0 else np.ones(n) / n

    shifts = w_opt - w_mkt

    return BlackLittermanResult(
        assets=assets,
        equilibrium_returns=dict(zip(assets, pi)),
        posterior_returns=dict(zip(assets, mu_bl)),
        prior_weights=dict(zip(assets, w_mkt)),
        optimal_weights=dict(zip(assets, w_opt)),
        weight_shifts=dict(zip(assets, shifts)),
        views_applied=views,
    )
